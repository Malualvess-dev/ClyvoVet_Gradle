CREATE TABLE TB_CV_PET (
    ID_PET        NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_TUTOR      NUMBER(19)   NOT NULL,
    NOME          VARCHAR2(60) NOT NULL,
    ESPECIE       VARCHAR2(20) NOT NULL,
    RACA          VARCHAR2(60),
    DT_NASCIMENTO DATE         NOT NULL,
    PESO_KG       NUMBER(5, 2) NOT NULL,
    CONSTRAINT FK_CV_PET_TUTOR FOREIGN KEY (ID_TUTOR) REFERENCES TB_CV_TUTOR (ID_TUTOR),
    CONSTRAINT CK_CV_PET_ESPECIE CHECK (ESPECIE IN ('CACHORRO', 'GATO', 'AVE', 'ROEDOR', 'OUTRO'))
);

CREATE TABLE TB_CV_CONSULTA (
    ID_CONSULTA    NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_PET         NUMBER(19)     NOT NULL,
    ID_VETERINARIO NUMBER(19)     NOT NULL,
    DATA_HORA      TIMESTAMP      NOT NULL,
    MOTIVO         VARCHAR2(250)  NOT NULL,
    STATUS         VARCHAR2(20)   NOT NULL,
    JUSTIFICATIVA  VARCHAR2(250),
    DATA_CRIACAO   TIMESTAMP      NOT NULL,
    CONSTRAINT FK_CV_CONSULTA_PET FOREIGN KEY (ID_PET) REFERENCES TB_CV_PET (ID_PET),
    CONSTRAINT FK_CV_CONSULTA_VETERINARIO FOREIGN KEY (ID_VETERINARIO) REFERENCES TB_CV_VETERINARIO (ID_VETERINARIO),
    CONSTRAINT CK_CV_CONSULTA_STATUS CHECK (STATUS IN ('SOLICITADA', 'CONFIRMADA', 'RECUSADA', 'CANCELADA', 'CONCLUIDA'))
);

CREATE INDEX IX_CV_CONSULTA_VET_DATA ON TB_CV_CONSULTA (ID_VETERINARIO, DATA_HORA);

CREATE TABLE TB_CV_NOTIFICACAO (
    ID_NOTIFICACAO NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_USUARIO     NUMBER(19)    NOT NULL,
    MENSAGEM       VARCHAR2(250) NOT NULL,
    DATA_ENVIO     TIMESTAMP     NOT NULL,
    DATA_LEITURA   TIMESTAMP,
    CONSTRAINT FK_CV_NOTIFICACAO_USUARIO FOREIGN KEY (ID_USUARIO) REFERENCES TB_CV_USUARIO (ID_USUARIO)
);
