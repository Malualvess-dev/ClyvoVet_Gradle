-- =============================================================================
-- Estrutura relacional do ClyvoVet (modelo da disciplina de Banco de Dados).
--
-- Mesmas tabelas, chaves, constraints e sequences do script scripts.sql do grupo,
-- com quatro diferenças, todas marcadas com [Java]:
--   * os ALTER TABLE ... MODIFY do script original já vêm aplicados nas colunas;
--   * SENHA e TIPO_USER aceitam nulo (login com Google/GitHub e perfil pendente);
--   * FOTO_URL do pet aceita nulo (a aplicação não exige foto);
--   * COMPLEMENTO, LATITUDE e LONGITUDE do endereço aceitam nulo.
-- Nenhuma mudança quebra o backend C#: só relaxam regras que já existiam.
-- =============================================================================

CREATE TABLE TB_ESTADO (
    ID_ESTADO NUMBER(6)          NOT NULL,
    NOME      VARCHAR2(60 CHAR)  NOT NULL,
    UF        CHAR(2 CHAR)       NOT NULL,
    CONSTRAINT PK_ESTADO PRIMARY KEY (ID_ESTADO),
    CONSTRAINT UN_ESTADO_UF UNIQUE (UF)
);

CREATE TABLE TB_CIDADE (
    ID_CIDADE NUMBER(6)          NOT NULL,
    NOME      VARCHAR2(100 CHAR) NOT NULL,
    ID_ESTADO NUMBER(6)          NOT NULL,
    CONSTRAINT PK_CIDADE PRIMARY KEY (ID_CIDADE)
);

CREATE TABLE TB_BAIRRO (
    ID_BAIRRO NUMBER(6)          NOT NULL,
    NOME      VARCHAR2(100 CHAR) NOT NULL,
    ID_CIDADE NUMBER(6)          NOT NULL,
    CONSTRAINT PK_BAIRRO PRIMARY KEY (ID_BAIRRO)
);

CREATE TABLE TB_USUARIO (
    ID_USUARIO   NUMBER(6)          NOT NULL,
    EMAIL        VARCHAR2(80 CHAR)  NOT NULL,
    SENHA        VARCHAR2(100 CHAR),                 -- [Java] nulo para login via Google/GitHub
    TIPO_USER    VARCHAR2(35 CHAR),                  -- [Java] nulo enquanto o perfil não é escolhido
    DATA_CRIACAO TIMESTAMP          NOT NULL,
    CONSTRAINT PK_USUARIO PRIMARY KEY (ID_USUARIO),
    CONSTRAINT UN_USUARIO_EMAIL UNIQUE (EMAIL),
    CONSTRAINT CK_USUARIO_TIPO CHECK (TIPO_USER IN ('TUTOR', 'VETERINARIO'))
);

CREATE TABLE TB_ENDERECO (
    ID_ENDERECO NUMBER(6)          NOT NULL,
    LOGRADOURO  VARCHAR2(120 CHAR) NOT NULL,
    NUMERO      VARCHAR2(10 CHAR)  NOT NULL,
    COMPLEMENTO VARCHAR2(50 CHAR),                   -- [Java] opcional
    CEP         VARCHAR2(9 CHAR)   NOT NULL,
    LATITUDE    NUMBER(10, 8),                       -- [Java] opcional
    LONGITUDE   NUMBER(11, 8),                       -- [Java] opcional
    ID_USUARIO  NUMBER(6)          NOT NULL,
    ID_BAIRRO   NUMBER(6)          NOT NULL,
    CONSTRAINT PK_ENDERECO PRIMARY KEY (ID_ENDERECO)
);

CREATE TABLE TB_TUTOR (
    ID_TUTOR      NUMBER(6)          NOT NULL,
    NOME_TUTOR    VARCHAR2(100 CHAR) NOT NULL,
    CPF           VARCHAR2(14 CHAR)  NOT NULL,
    TELEFONE      VARCHAR2(15 CHAR)  NOT NULL,
    DT_NASCIMENTO DATE               NOT NULL,
    ID_USUARIO    NUMBER(6)          NOT NULL,
    CONSTRAINT PK_TUTOR PRIMARY KEY (ID_TUTOR),
    CONSTRAINT UN_TUTOR_CPF UNIQUE (CPF)
);

CREATE UNIQUE INDEX TB_TUTOR__IDX ON TB_TUTOR (ID_USUARIO ASC);

CREATE TABLE TB_VETERINARIO (
    ID_VETERINARIO NUMBER(6)          NOT NULL,
    NOME           VARCHAR2(100 CHAR) NOT NULL,
    CRMV           VARCHAR2(14 CHAR)  NOT NULL,
    TELEFONE       VARCHAR2(15 CHAR)  NOT NULL,
    ESPECIALIDADE  VARCHAR2(100 CHAR) NOT NULL,
    DT_NASCIMENTO  DATE               NOT NULL,
    ID_USUARIO     NUMBER(6)          NOT NULL,
    CONSTRAINT PK_VETERINARIO PRIMARY KEY (ID_VETERINARIO),
    CONSTRAINT UN_VETERINARIO_CRMV UNIQUE (CRMV),
    CONSTRAINT CK_VETERINARIO_CRMV CHECK (REGEXP_LIKE(CRMV, '^CRMV-[A-Z]{2}-[0-9]{5}$'))
);

CREATE UNIQUE INDEX TB_VETERINARIO__IDX ON TB_VETERINARIO (ID_USUARIO ASC);

CREATE TABLE TB_ESPECIE (
    ID_ESPECIE NUMBER(6)         NOT NULL,
    NOME       VARCHAR2(50 CHAR) NOT NULL,
    CONSTRAINT PK_ESPECIE PRIMARY KEY (ID_ESPECIE)
);

CREATE TABLE TB_RACA (
    ID_RACA    NUMBER(6)          NOT NULL,
    NOME       VARCHAR2(100 CHAR) NOT NULL,
    PORTE      VARCHAR2(10 CHAR)  NOT NULL,
    ID_ESPECIE NUMBER(6)          NOT NULL,
    CONSTRAINT PK_RACA PRIMARY KEY (ID_RACA),
    CONSTRAINT CK_RACA_PORTE CHECK (PORTE IN ('PEQUENO', 'MEDIO', 'GRANDE'))
);

CREATE TABLE TB_PET (
    ID_PET        NUMBER(6)          NOT NULL,
    NOME          VARCHAR2(50 CHAR)  NOT NULL,
    DT_NASCIMENTO DATE               NOT NULL,
    SEXO          CHAR(1 CHAR)       NOT NULL,
    FOTO_URL      VARCHAR2(255 CHAR),                -- [Java] opcional
    ID_TUTOR      NUMBER(6)          NOT NULL,
    ID_RACA       NUMBER(6)          NOT NULL,
    CONSTRAINT PK_PET PRIMARY KEY (ID_PET),
    CONSTRAINT CK_PET_SEXO CHECK (SEXO IN ('M', 'F'))
);

CREATE TABLE TB_CONSULTA (
    ID_CONSULTA    NUMBER(6)           NOT NULL,
    DATA_HORA      TIMESTAMP           NOT NULL,
    MODALIDADE     VARCHAR2(15 CHAR)   NOT NULL,
    STATUS         VARCHAR2(15 CHAR)   NOT NULL,
    OBSERVACOES    VARCHAR2(1000 CHAR),
    ID_PET         NUMBER(6)           NOT NULL,
    ID_VETERINARIO NUMBER(6)           NOT NULL,
    CONSTRAINT PK_CONSULTA PRIMARY KEY (ID_CONSULTA),
    CONSTRAINT CK_CONSULTA_STATUS CHECK (STATUS IN ('AGENDADA', 'REALIZADA', 'CANCELADA')),
    CONSTRAINT CK_CONSULTA_MODALIDADE CHECK (MODALIDADE IN ('ONLINE', 'PRESENCIAL'))
);

CREATE TABLE TB_PRONTUARIO (
    ID_PRONTUARIO      NUMBER(6)          NOT NULL,
    DIAGNOSTICO        VARCHAR2(500 CHAR) NOT NULL,
    TRATAMENTO         VARCHAR2(500 CHAR),
    SINTOMAS           VARCHAR2(250 CHAR),
    PESO_ANIMAL        NUMBER(5, 2),
    TEMPERATURA        NUMBER(4, 1),
    EXAMES_SOLICITADOS VARCHAR2(250 CHAR),
    DATA_RETORNO       DATE,
    ID_CONSULTA        NUMBER(6)          NOT NULL,
    CONSTRAINT PK_PRONTUARIO PRIMARY KEY (ID_PRONTUARIO)
);

CREATE UNIQUE INDEX TB_PRONTUARIO__IDX ON TB_PRONTUARIO (ID_CONSULTA ASC);

CREATE TABLE TB_PRESCRICAO (
    ID_PRESCRICAO NUMBER(6)          NOT NULL,
    TIPO          VARCHAR2(15 CHAR)  NOT NULL,
    DESCRICAO     VARCHAR2(200 CHAR) NOT NULL,
    POSOLOGIA     VARCHAR2(350 CHAR),
    ID_PRONTUARIO NUMBER(6)          NOT NULL,
    CONSTRAINT PK_PRESCRICAO PRIMARY KEY (ID_PRESCRICAO),
    CONSTRAINT CK_PRESCRICAO_TIPO CHECK (TIPO IN ('MEDICAMENTO', 'DIETA', 'RESTRICAO'))
);

CREATE TABLE TB_HISTORICO_SAUDE (
    ID_HISTORICO_SAUDE NUMBER(6)          NOT NULL,
    EVENTO             VARCHAR2(100 CHAR) NOT NULL,
    DATA_EVENTO        DATE               NOT NULL,
    DETALHES           VARCHAR2(200 CHAR),
    ID_PET             NUMBER(6)          NOT NULL,
    CONSTRAINT PK_HISTORICO_SAUDE PRIMARY KEY (ID_HISTORICO_SAUDE)
);

CREATE TABLE TB_COLEIRA (
    ID_COLEIRA    NUMBER(6)      NOT NULL,
    DATA_HORA     TIMESTAMP      NOT NULL,
    LATITUDE      NUMBER(10, 8)  NOT NULL,
    LONGITUDE     NUMBER(11, 8)  NOT NULL,
    BATIMENTO_BPM NUMBER(5, 1)   NOT NULL,
    ALERTA        NUMBER(1)      NOT NULL,
    ID_PET        NUMBER(6)      NOT NULL,
    CONSTRAINT PK_COLEIRA PRIMARY KEY (ID_COLEIRA)
);

CREATE TABLE TB_AUDITORIA_COLEIRA (
    ID_AUDITORIA   NUMBER(6)          NOT NULL,
    USUARIO        VARCHAR2(100 CHAR) NOT NULL,
    OPERACAO       VARCHAR2(10 CHAR)  NOT NULL,
    DATA_HORA      TIMESTAMP          NOT NULL,
    ID_COLEIRA_OLD NUMBER(6),
    ID_COLEIRA_NEW NUMBER(6),
    DATA_HORA_OLD  TIMESTAMP,
    DATA_HORA_NEW  TIMESTAMP,
    LATITUDE_OLD   NUMBER(10, 8),
    LATITUDE_NEW   NUMBER(10, 8),
    LONGITUDE_OLD  NUMBER(11, 8),
    LONGITUDE_NEW  NUMBER(11, 8),
    BATIMENTO_OLD  NUMBER(5, 1),
    BATIMENTO_NEW  NUMBER(5, 1),
    ALERTA_OLD     NUMBER(1),
    ALERTA_NEW     NUMBER(1),
    ID_PET_OLD     NUMBER(6),
    ID_PET_NEW     NUMBER(6),
    CONSTRAINT PK_AUDITORIA_COLEIRA PRIMARY KEY (ID_AUDITORIA)
);

CREATE TABLE TB_AGENDA (
    ID_AGENDA  NUMBER(6)           NOT NULL,
    TITULO     VARCHAR2(85 CHAR)   NOT NULL,
    DATA_HORA  TIMESTAMP           NOT NULL,
    ANOTACAO   VARCHAR2(2500 CHAR),
    ID_USUARIO NUMBER(6)           NOT NULL,
    CONSTRAINT PK_AGENDA PRIMARY KEY (ID_AGENDA)
);

CREATE TABLE TB_NOTIFICACAO (
    ID_NOTIFICACAO NUMBER(6)          NOT NULL,
    MENSAGEM       VARCHAR2(200 CHAR) NOT NULL,
    DATA_ENVIO     TIMESTAMP          NOT NULL,
    LIDA           CHAR(1)            NOT NULL,
    ID_USUARIO     NUMBER(6)          NOT NULL,
    CONSTRAINT PK_NOTIFICACAO PRIMARY KEY (ID_NOTIFICACAO),
    CONSTRAINT CK_NOTIFICACAO_LIDA CHECK (LIDA IN ('S', 'N'))
);

CREATE TABLE TB_ANEXO (
    ID_ANEXO     NUMBER(6)          NOT NULL,
    NOME_ARQUIVO VARCHAR2(255 CHAR) NOT NULL,
    TIPO_ARQUIVO VARCHAR2(50 CHAR)  NOT NULL,
    URL          VARCHAR2(255 CHAR) NOT NULL,
    TAMANHO_KB   NUMBER,
    DATA_CRIACAO TIMESTAMP          NOT NULL,
    ID_USUARIO   NUMBER(6)          NOT NULL,
    CONSTRAINT PK_ANEXO PRIMARY KEY (ID_ANEXO)
);

CREATE TABLE TB_LOG_ERRO (
    ID_LOG_ERRO    NUMBER(6)           NOT NULL,
    NOME_PROCEDURE VARCHAR2(100 CHAR)  NOT NULL,
    NOME_USUARIO   VARCHAR2(100 CHAR)  NOT NULL,
    DATA_ERRO      TIMESTAMP           NOT NULL,
    CODIGO_ERRO    NUMBER              NOT NULL,
    MENSAGEM_ERRO  VARCHAR2(4000 CHAR) NOT NULL,
    CONSTRAINT TB_LOG_ERRO_PK PRIMARY KEY (ID_LOG_ERRO)
);

