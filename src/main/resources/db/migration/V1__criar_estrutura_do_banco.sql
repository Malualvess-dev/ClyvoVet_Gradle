ALTER TABLE TB_CONSULTA ADD CONSTRAINT FK_CONSULTA_PET FOREIGN KEY (ID_PET) REFERENCES TB_PET (ID_PET);
ALTER TABLE TB_CONSULTA ADD CONSTRAINT FK_CONSULTA_VETERINARIO FOREIGN KEY (ID_VETERINARIO) REFERENCES TB_VETERINARIO (ID_VETERINARIO);
ALTER TABLE TB_PRONTUARIO ADD CONSTRAINT FK_PRONTUARIO_CONSULTA FOREIGN KEY (ID_CONSULTA) REFERENCES TB_CONSULTA (ID_CONSULTA);
ALTER TABLE TB_PRESCRICAO ADD CONSTRAINT FK_PRESCRICAO_PRONTUARIO FOREIGN KEY (ID_PRONTUARIO) REFERENCES TB_PRONTUARIO (ID_PRONTUARIO);
ALTER TABLE TB_HISTORICO_SAUDE ADD CONSTRAINT FK_HISTORICO_SAUDE_PET FOREIGN KEY (ID_PET) REFERENCES TB_PET (ID_PET);
ALTER TABLE TB_COLEIRA ADD CONSTRAINT FK_COLEIRA_PET FOREIGN KEY (ID_PET) REFERENCES TB_PET (ID_PET);
ALTER TABLE TB_AGENDA ADD CONSTRAINT FK_AGENDA_USUARIO FOREIGN KEY (ID_USUARIO) REFERENCES TB_USUARIO (ID_USUARIO);
ALTER TABLE TB_NOTIFICACAO ADD CONSTRAINT FK_NOTIFICACAO_USUARIO FOREIGN KEY (ID_USUARIO) REFERENCES TB_USUARIO (ID_USUARIO);
ALTER TABLE TB_ANEXO ADD CONSTRAINT FK_ANEXO_USUARIO FOREIGN KEY (ID_USUARIO) REFERENCES TB_USUARIO (ID_USUARIO);

